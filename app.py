@app.route("/business/register", methods=["GET", "POST"])
def business_register():

    if request.method == "POST":

        business_name = request.form.get(
            "business_name", ""
        ).strip()

        email = request.form.get(
            "email", ""
        ).strip().lower()

        password = request.form.get("password", "")

        role = request.form.get("role", "").strip()

        phone = request.form.get("phone", "").strip()

        whatsapp = request.form.get("whatsapp", "").strip()

        allowed_roles = [
            "Manufacturer",
            "Wholesaler",
            "Retailer"
        ]

        if not business_name or not email or not password:
            flash("Please complete all required fields.")
            return redirect(url_for("business_register"))

        if role not in allowed_roles:
            flash("Please select a valid business role.")
            return redirect(url_for("business_register"))

        if len(password) < 8:
            flash("Your password must be at least 8 characters.")
            return redirect(url_for("business_register"))

        connection = get_db()

        try:
            connection.execute(
                """
                INSERT INTO businesses
                (
                    business_name,
                    email,
                    password_hash,
                    role,
                    phone,
                    whatsapp,
                    created_at
                )
                VALUES (%s, %s, %s, %s, %s, %s, %s)
                """,
                (
                    business_name,
                    email,
                    generate_password_hash(password),
                    role,
                    phone,
                    whatsapp,
                    current_time()
                )
            )

            connection.commit()

        except IntegrityError:
            connection.rollback()
            flash("This email is already registered.")
            return redirect(url_for("business_register"))

        finally:
            connection.close()

        flash("Business account created. Please log in.")

        return redirect(url_for("business_login"))

    return render_template("business_register.html")


