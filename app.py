@app.route("/")
def home():
    connection = get_db()

    try:
        products = connection.execute(
            """
            SELECT *
            FROM products
            ORDER BY created_at DESC
            """
        ).fetchall()

    finally:
        connection.close()

    return render_template(
        "index.html",
        products=products
    )


