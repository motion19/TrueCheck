@app.route("/barcode")
def check_barcode():
    barcode = request.args.get("code", "").strip()

    if not barcode:
        return "No barcode was provided.", 400

    connection = get_db()

    try:
        product = connection.execute(
            """
            SELECT id
            FROM products
            WHERE barcode = %s
            """,
            (barcode,)
        ).fetchone()

    finally:
        connection.close()

    if product:
        return redirect(
            url_for(
                "verify_product",
                product_id=product["id"]
            )
        )

    return (
        "This barcode is not registered in TrueCheck. "
        "Authenticity cannot be confirmed."
    ), 404


