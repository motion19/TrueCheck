def get_db():
    database_url = os.environ.get("DATABASE_URL")

    if not database_url:
        raise RuntimeError("DATABASE_URL is not configured.")

    return psycopg.connect(
        database_url,
        row_factory=dict_row
    )


# --------------------------------
# DATE AND TIME
# --------------------------------

def current_time():
    return datetime.now(timezone.utc).strftime(
        "%Y-%m-%d %H:%M:%S"
    )


# --------------------------------
# DATABASE SETUP
# --------------------------------

def setup_database():
    connection = get_db()

    try:
        connection.execute("""
            CREATE TABLE IF NOT EXISTS businesses (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                business_name TEXT NOT NULL,
                email TEXT NOT NULL UNIQUE,
                password_hash TEXT NOT NULL,
                role TEXT NOT NULL,
                created_at TEXT NOT NULL
            )
        """)

        connection.execute("""
            ALTER TABLE businesses
            ADD COLUMN IF NOT EXISTS phone TEXT
        """)

        connection.execute("""
            ALTER TABLE businesses
            ADD COLUMN IF NOT EXISTS whatsapp TEXT
        """)

        connection.execute("""
            CREATE TABLE IF NOT EXISTS products (
                id TEXT PRIMARY KEY,
                name TEXT NOT NULL,
                batch TEXT,
                barcode TEXT,
                status TEXT NOT NULL,
                created_at TEXT NOT NULL
            )
        """)

        connection.execute("""
            ALTER TABLE products
            ADD COLUMN IF NOT EXISTS barcode TEXT
        """)

        # PRODUCT IMAGE URL
        connection.execute("""
            ALTER TABLE products
            ADD COLUMN IF NOT EXISTS image_url TEXT
        """)

        connection.execute("""
            CREATE TABLE IF NOT EXISTS events (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                product_id TEXT NOT NULL,
                event TEXT NOT NULL,
                actor TEXT NOT NULL,
                created_at TEXT NOT NULL
            )
        """)

        connection.execute("""
            CREATE TABLE IF NOT EXISTS retailer_listings (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                retailer_id BIGINT NOT NULL
                    REFERENCES businesses(id),
                product_id TEXT NOT NULL
                    REFERENCES products(id),
                price NUMERIC(12, 2) NOT NULL
                    CHECK (price > 0),
                available BOOLEAN NOT NULL DEFAULT TRUE,
                created_at TEXT NOT NULL,
                UNIQUE (retailer_id, product_id)
            )
        """)

        connection.execute("""
            CREATE TABLE IF NOT EXISTS orders (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                order_reference TEXT NOT NULL UNIQUE,
                customer_name TEXT NOT NULL,
                customer_phone TEXT NOT NULL,
                delivery_address TEXT NOT NULL,
                retailer_id BIGINT NOT NULL
                    REFERENCES businesses(id),
                payment_method TEXT NOT NULL
                    CHECK (
                        payment_method IN (
                            'cash_on_delivery',
                            'bank_transfer',
                            'online'
                        )
                    ),
                payment_status TEXT NOT NULL DEFAULT 'pending',
                order_status TEXT NOT NULL DEFAULT 'pending',
                created_at TEXT NOT NULL
            )
        """)

        connection.execute("""
            CREATE TABLE IF NOT EXISTS order_items (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                order_id BIGINT NOT NULL
                    REFERENCES orders(id) ON DELETE CASCADE,
                product_id TEXT NOT NULL
                    REFERENCES products(id),
                product_name TEXT NOT NULL,
                quantity INTEGER NOT NULL CHECK (quantity > 0),
                unit_price NUMERIC(12, 2) NOT NULL
                    CHECK (unit_price > 0)
            )
        """)

        connection.execute("""
            CREATE INDEX IF NOT EXISTS idx_listings_retailer
            ON retailer_listings(retailer_id)
        """)

        connection.execute("""
            CREATE INDEX IF NOT EXISTS idx_orders_retailer
            ON orders(retailer_id)
        """)

        connection.execute("""
            CREATE INDEX IF NOT EXISTS idx_order_items_order
            ON order_items(order_id)
        """)

        connection.execute("""
            CREATE INDEX IF NOT EXISTS idx_events_product
            ON events(product_id)
        """)

        connection.commit()

    except Exception:
        connection.rollback()
        raise

    finally:
        connection.close()


