@app.route(
    "/seller/toggle-listing/<int:listing_id>",
    methods=["POST"]
)
def seller_toggle_listing(listing_id):

    if "business_id" not in session:
        return redirect(url_for("business_login"))

    connection = get_db()

    try:
        listing = connection.execute(
            """
            SELECT id, available
            FROM retailer_listings
            WHERE id = %s
              AND retailer_id = %s
            """,
            (
                listing_id,
                session["business_id"]
            )
        ).fetchone()

        if listing is None:
            flash("Listing not found.")
            return redirect(url_for("seller_dashboard"))

        new_status = not listing["available"]

        connection.execute(
            """
            UPDATE retailer_listings
            SET available = %s
            WHERE id = %s
              AND retailer_id = %s
            """,
            (
                new_status,
                listing_id,
                session["business_id"]
            )
        )

        connection.commit()

        flash("Product listing availability updated.")

    except Exception:
        connection.rollback()
        app.logger.exception("Updating listing failed.")
        flash("Could not update product availability.")

    finally:
        connection.close()

    return redirect(url_for("seller_dashboard"))

