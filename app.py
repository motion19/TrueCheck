@app.route("/transfer/<product_id>", methods=["POST"])
def transfer_product(product_id):
    if "business_id" not in session:
        flash("Please log in to transfer products.")
        return redirect(url_for("business_login"))

    role = session.get("role", "").strip()
    actor = session.get("business_name", "").strip()

    allowed_destinations = {
        "Manufacturer": "Wholesaler",
        "Wholesaler": "Retailer"
    }

    destination = allowed_destinations.get(role)

    if not destination:
        flash("Your business role cannot transfer this product.")
        return redirect(
            url_for("verify_product", product_id=product_id)
        )

    connection = get_db()

    try:
        product = connection.execute(
            """
            SELECT id, status
            FROM products
            WHERE id = %s
            FOR UPDATE
            """,
            (product_id,)
        ).fetchone()

        if product is None:
            flash("Product not found.")
            return redirect(url_for("home"))

        expected_status = f"With {role}"

        if product["status"] != expected_status:
            flash(
                f"Transfer rejected. Product status is currently "
                f"{product['status']}."
            )
            connection.rollback()
            return redirect(
                url_for("verify_product", product_id=product_id)
            )

        new_status = f"With {destination}"

        connection.execute(
            """
            UPDATE products
            SET status = %s
            WHERE id = %s
            """,
            (new_status, product_id)
        )

        connection.execute(
            """
            INSERT INTO events
            (product_id, event, actor, created_at)
            VALUES (%s, %s, %s, %s)
            """,
            (
                product_id,
                f"Transferred to {destination}",
                actor,
                current_time()
            )
        )

        connection.commit()

        flash(
            f"Transfer successful! Product is now with {destination}."
        )

    except Exception:
        connection.rollback()
        app.logger.exception("Product transfer failed.")
        flash("Transfer failed because of a database error.")

    finally:
        connection.close()

    return redirect(
        url_for("verify_product", product_id=product_id)
    )

