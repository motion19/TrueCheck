@app.route("/register", methods=["POST"])
def register_product():
    if "business_id" not in session:
        flash("Please log in to register a product.")
        return redirect(url_for("business_login"))

    if session.get("role") != "Manufacturer":
        flash("Only manufacturers can register products.")
        return redirect(url_for("home"))

    name = request.form.get("name", "").strip()
    batch = request.form.get("batch", "").strip()
    barcode = request.form.get("barcode", "").strip()

    if not name:
        flash("Product name is required.")
        return redirect(url_for("home"))

    product_id = (
        "TC-NG-"
        + datetime.now().strftime("%Y%m%d")
        + "-"
        + uuid.uuid4().hex[:8].upper()
    )

    manufacturer = session.get("business_name", "").strip()

    connection = get_db()

    try:
        connection.execute(
            """
            INSERT INTO products
            (id, name, batch, barcode, status, created_at)
            VALUES (%s, %s, %s, %s, %s, %s)
            """,
            (
                product_id,
                name,
                batch,
                barcode or None,
                "With Manufacturer",
                current_time()
            )
        )

        connection.commit()

    except Exception:
        connection.rollback()
        raise

    finally:
        connection.close()

    add_event(
        product_id,
        "Product registered",
        manufacturer
    )

    return redirect(
        url_for("show_qr", product_id=product_id)
    )


