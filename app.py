def add_event(product_id, event, actor):
    connection = get_db()

    try:
        connection.execute(
            """
            INSERT INTO events
            (product_id, event, actor, created_at)
            VALUES (%s, %s, %s, %s)
            """,
            (
                product_id,
                event,
                actor,
                current_time()
            )
        )

        connection.commit()

    except Exception:
        connection.rollback()
        raise

    finally:
        connection.close()


