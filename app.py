@app.route(
    "/seller/listing",
    methods=["POST"]
)
def create_listing():

    if "business_id" not in session:
        flash("Please log in first.")
        return redirect(url_for("business_login"))

    if session.get("role") != "Retailer":
        flash("Only retailers can create product listings.")
        return redirect(url_for("home"))

    product_id = request.form.get(
        "product_id", ""
    ).strip()

    price = request.form.get(
        "price", ""
    ).strip()

    try:
        price = float(price)

        if price <= 0:
            raise ValueError

    except ValueError:
        flash("Please enter a valid product price.")
        return redirect(url_for("seller_dashboard"))

    connection = get_db()

    try:
        product = connection.execute(
            """
            SELECT *
            FROM products
            WHERE id = %s
            """,
            (product_id,)
        ).fetchone()

        if not product:
            flash("Product not found.")
            return redirect(url_for("seller_dashboard"))

        if product["status"] != "With Retailer":
            flash("Only products received by retailers can be listed.")
            return redirect(url_for("seller_dashboard"))

        connection.execute(
            """
            INSERT INTO retailer_listings
            (
                retailer_id,
                product_id,
                price,
                available,
                created_at
            )
            VALUES (%s, %s, %s, TRUE, %s)
            ON CONFLICT (retailer_id, product_id)
            DO UPDATE SET
                price = EXCLUDED.price,
                available = TRUE
            """,
            (
                session["business_id"],
                product_id,
                price,
                current_time()
            )
        )

        connection.commit()

        flash("Product listing saved.")

    except Exception:
        connection.rollback()
        app.logger.exception("Listing creation failed.")
        flash("Could not save product listing.")

    finally:
        connection.close()

    return redirect(url_for("seller_dashboard"))


