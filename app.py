@app.route("/verify/<product_id>")
def verify_product(product_id):
    connection = get_db()

    try:
        product = connection.execute(
            """
            SELECT *
            FROM products
            WHERE id = %s
            """,
            (product_id,)
        ).fetchone()

        events = connection.execute(
            """
            SELECT *
            FROM events
            WHERE product_id = %s
            ORDER BY id
            """,
            (product_id,)
        ).fetchall()

    finally:
        connection.close()

    if product is None:
        return "Product not found.", 404

    return render_template(
        "verify.html",
        product=product,
        events=events
    )


